/// Classification of a span's role in the call chain.
///
/// Mirrors the OpenTelemetry [SpanKind] semantic conventions.
///
/// [SpanKind]: https://opentelemetry.io/docs/specs/otel/trace/api/#spankind
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum SpanKind {
    /// Default — opaque local work (a function call, an internal job).
    Internal,
    /// Outbound call to a remote service.
    Client,
    /// Inbound call served to a remote caller.
    Server,
    /// Producer half of a message-queue exchange.
    Producer,
    /// Consumer half of a message-queue exchange.
    Consumer,
}

/// Final status assigned to a span before it is closed.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "status", rename_all = "lowercase")]
pub enum SpanStatus {
    /// Status has not been set — typically the value carried by an in-flight
    /// span before the caller signals success or failure.
    Unset,
    /// Operation completed successfully.
    Ok,
    /// Operation failed; `message` carries a human-readable cause.
    Error {
        /// Human-readable cause of the failure.
        message: String,
    },
}

impl Default for SpanStatus {
    fn default() -> Self {
        Self::Unset
    }
}

/// A point-in-time event attached to a span.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SpanEvent {
    /// Wall-clock timestamp of when the event was recorded.
    pub ts: DateTime<Utc>,
    /// Event name (e.g. `cache.miss`, `retry.scheduled`).
    pub name: String,
    /// Free-form structured attributes attached to the event.
    #[serde(default)]
    pub attributes: HashMap<String, serde_json::Value>,
}

/// A finalized span ready for export. Lives entirely in memory; consumers
/// retrieve a copy via [`Telemetry::dump_spans`].
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Span {
    /// Stable, monotonic span identifier.
    pub id: SpanId,
    /// Owning trace; every span in the same logical operation shares this id.
    pub trace_id: TraceId,
    /// Parent span identifier; `None` marks the root span of a trace.
    #[serde(default)]
    pub parent: Option<SpanId>,
    /// Free-form name (the operation being timed).
    pub name: String,
    /// Classification of this span's role.
    pub kind: SpanKind,
    /// Wall-clock start.
    pub start: DateTime<Utc>,
    /// Wall-clock end — `None` while the span is still in-flight.
    #[serde(default)]
    pub end: Option<DateTime<Utc>>,
    /// Final status; defaults to [`SpanStatus::Unset`] for in-flight spans.
    #[serde(default)]
    pub status: SpanStatus,
    /// Free-form structured attributes.
    #[serde(default)]
    pub attributes: HashMap<String, serde_json::Value>,
    /// Ordered point-in-time events attached to this span.
    #[serde(default)]
    pub events: Vec<SpanEvent>,
}

impl Span {
    /// Wall-clock duration in milliseconds; `None` while the span is in-flight.
    #[must_use]
    pub fn duration_ms(&self) -> Option<u64> {
        self.end.map(|end| {
            let delta = end - self.start;
            let ms = delta.num_milliseconds();
            if ms < 0 { 0 } else { ms as u64 }
        })
    }

    /// Insert / overwrite a single attribute.
    pub fn set_attribute(&mut self, key: impl Into<String>, value: impl Into<serde_json::Value>) {
        self.attributes.insert(key.into(), value.into());
    }

    /// Append a structured event to this span. The timestamp is stamped from
    /// `Utc::now()` at append time.
    pub fn add_event(
        &mut self,
        name: impl Into<String>,
        attributes: HashMap<String, serde_json::Value>,
    ) {
        self.events.push(SpanEvent {
            ts: Utc::now(),
            name: name.into(),
            attributes,
        });
    }

    /// Close the span by stamping `end = Utc::now()` and assigning `status`.
    pub fn end_with_status(&mut self, status: SpanStatus) {
        self.end = Some(Utc::now());
        self.status = status;
    }

    /// Return `true` once `end` has been stamped.
    #[must_use]
    pub fn is_ended(&self) -> bool {
        self.end.is_some()
    }
}

