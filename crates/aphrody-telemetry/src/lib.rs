/// All recoverable failures emitted by this crate.
///
/// Shape modelled after `aphrody_session::SessionError` — opaque transparent
/// forwards for IO and JSON, named variants for domain errors.
#[derive(Debug, Error)]
pub enum TelemetryError {
    /// Filesystem error while exporting an NDJSON batch.
    #[error("io error: {0}")]
    Io(#[from] std::io::Error),
    /// JSON serialization of a span failed.
    #[error("json error: {0}")]
    Json(#[from] serde_json::Error),
    /// `end()` was called twice on the same `SpanHandle`, or the underlying
    /// span was finalized through some other path before the handle dropped.
    #[error("span already ended")]
    SpanAlreadyEnded,
    /// `Telemetry::histogram` was called with an empty bucket list. Histograms
    /// require at least one upper bound, sorted ascending.
    #[error("histogram requires at least one bucket upper bound")]
    HistogramBucketsRequired,
}

// ---------------------------------------------------------------------------
// SpanId / TraceId — monotonic process-local newtypes
// ---------------------------------------------------------------------------

/// Process-local monotonic span identifier.
///
/// Generated by [`SpanId::generate`] from a single atomic counter; the first
/// id is always non-zero (the counter is seeded from the current wall clock
/// on first use).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct SpanId(u64);

impl SpanId {
    /// Allocate a fresh, monotonically increasing identifier.
    #[must_use]
    pub fn generate() -> Self {
        static COUNTER: AtomicU64 = AtomicU64::new(0);
        seed_then_bump(&COUNTER)
    }

    /// Borrow the raw underlying `u64`.
    #[must_use]
    pub const fn as_u64(self) -> u64 {
        self.0
    }
}

impl fmt::Display for SpanId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "span-{:016x}", self.0)
    }
}

/// Process-local monotonic trace identifier.
///
/// Generated by [`TraceId::generate`] from a single atomic counter; carries no
/// hierarchical link by itself — every span in the same trace shares the same
/// `TraceId`, and parent/child relationships are encoded through
/// [`Span::parent`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct TraceId(u64);

impl TraceId {
    /// Allocate a fresh, monotonically increasing identifier.
    #[must_use]
    pub fn generate() -> Self {
        static COUNTER: AtomicU64 = AtomicU64::new(0);
        seed_then_bump(&COUNTER)
    }

    /// Borrow the raw underlying `u64`.
    #[must_use]
    pub const fn as_u64(self) -> u64 {
        self.0
    }
}

impl fmt::Display for TraceId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "trace-{:016x}", self.0)
    }
}

/// Helper that seeds the supplied counter from the wall clock on first use,
/// then returns `counter.fetch_add(1) + 1` wrapped in `T::from(u64)`.
fn seed_then_bump<T: From<u64>>(counter: &AtomicU64) -> T {
    let seed_from_clock: u64 = chrono::Utc::now()
        .timestamp_nanos_opt()
        .and_then(|n| u64::try_from(n).ok())
        .unwrap_or(1);
    let _ = counter.compare_exchange(
        0,
        seed_from_clock | 1,
        Ordering::Relaxed,
        Ordering::Relaxed,
    );
    let raw = counter.fetch_add(1, Ordering::Relaxed).wrapping_add(1);
    T::from(raw)
}

impl From<u64> for SpanId {
    fn from(v: u64) -> Self {
        Self(v)
    }
}

impl From<u64> for TraceId {
    fn from(v: u64) -> Self {
        Self(v)
    }
}

