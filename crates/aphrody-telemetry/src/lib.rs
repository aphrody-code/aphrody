/// Monotonic `u64` accumulator. Thread-safe.
///
/// Created lazily via [`Telemetry::counter`] — repeated registrations of the
/// same name return the same `Arc<Counter>`, so producers and the exporter
/// observe the same underlying state.
#[derive(Debug)]
pub struct Counter {
    name: String,
    value: AtomicU64,
}

impl Counter {
    fn new(name: impl Into<String>) -> Self {
        Self {
            name: name.into(),
            value: AtomicU64::new(0),
        }
    }

    /// Counter name (immutable post-construction).
    #[must_use]
    pub fn name(&self) -> &str {
        &self.name
    }

    /// Atomically increment by one.
    pub fn inc(&self) {
        self.value.fetch_add(1, Ordering::Relaxed);
    }

    /// Atomically add `n`.
    pub fn add(&self, n: u64) {
        self.value.fetch_add(n, Ordering::Relaxed);
    }

    /// Read the current value with `Relaxed` ordering.
    #[must_use]
    pub fn value(&self) -> u64 {
        self.value.load(Ordering::Relaxed)
    }
}

// ---------------------------------------------------------------------------
// Histogram
// ---------------------------------------------------------------------------

/// Bucketed `f64` observation distribution.
///
/// Bucket counts follow the strict OpenTelemetry explicit-bucket model: each
/// bucket `i` counts observations with `value <= buckets[i]`. Values greater
/// than every supplied upper bound are **not** counted in any bucket but still
/// contribute to `sum` and `count` (consistent with Prometheus semantics —
/// callers that want a `+inf` bucket should append `f64::INFINITY` themselves).
#[derive(Debug)]
pub struct Histogram {
    name: String,
    buckets: Vec<f64>,
    counts: Vec<AtomicU64>,
    sum_micros: AtomicU64,
    count: AtomicU64,
}

impl Histogram {
    fn new(name: impl Into<String>, buckets: Vec<f64>) -> Result<Self, TelemetryError> {
        if buckets.is_empty() {
            return Err(TelemetryError::HistogramBucketsRequired);
        }
        let counts = (0..buckets.len()).map(|_| AtomicU64::new(0)).collect();
        Ok(Self {
            name: name.into(),
            buckets,
            counts,
            sum_micros: AtomicU64::new(0),
            count: AtomicU64::new(0),
        })
    }

    /// Histogram name.
    #[must_use]
    pub fn name(&self) -> &str {
        &self.name
    }

    /// Borrow the bucket upper bounds (caller-supplied at registration time).
    #[must_use]
    pub fn buckets(&self) -> &[f64] {
        &self.buckets
    }

    /// Record one observation. Values are routed to every bucket with
    /// `upper_bound >= value`, the global count is bumped, and the running sum
    /// is updated in microsecond fixed-point (×1_000_000) to dodge `f64`
    /// atomicity hazards.
    pub fn observe(&self, value: f64) {
        for (idx, &upper) in self.buckets.iter().enumerate() {
            if value <= upper {
                self.counts[idx].fetch_add(1, Ordering::Relaxed);
            }
        }
        self.count.fetch_add(1, Ordering::Relaxed);
        let micros = if value.is_finite() && value >= 0.0 {
            (value * 1_000_000.0) as u64
        } else {
            0
        };
        self.sum_micros.fetch_add(micros, Ordering::Relaxed);
    }

    /// Take a point-in-time snapshot of every counter. Cheap (one
    /// `Relaxed` load per bucket plus two more for sum + count).
    #[must_use]
    pub fn snapshot(&self) -> HistogramSnapshot {
        let bucket_counts = self
            .counts
            .iter()
            .map(|c| c.load(Ordering::Relaxed))
            .collect();
        let sum_micros = self.sum_micros.load(Ordering::Relaxed);
        HistogramSnapshot {
            name: self.name.clone(),
            buckets: self.buckets.clone(),
            bucket_counts,
            sum: (sum_micros as f64) / 1_000_000.0,
            count: self.count.load(Ordering::Relaxed),
        }
    }
}

/// Serializable point-in-time snapshot of a [`Histogram`].
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct HistogramSnapshot {
    /// Histogram name.
    pub name: String,
    /// Bucket upper bounds (mirrors `Histogram::buckets`).
    pub buckets: Vec<f64>,
    /// Per-bucket cumulative counts; `bucket_counts[i]` counts every
    /// observation with `value <= buckets[i]`.
    pub bucket_counts: Vec<u64>,
    /// Sum of every observed value.
    pub sum: f64,
    /// Total number of observations.
    pub count: u64,
}

/// Serializable point-in-time snapshot of a [`Counter`].
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CounterSnapshot {
    /// Counter name.
    pub name: String,
    /// Current value.
    pub value: u64,
}

/// Roll-up of every metric currently registered with a [`Telemetry`] handle.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MetricsSnapshot {
    /// One [`CounterSnapshot`] per registered counter, sorted by name.
    pub counters: Vec<CounterSnapshot>,
    /// One [`HistogramSnapshot`] per registered histogram, sorted by name.
    pub histograms: Vec<HistogramSnapshot>,
}

// ---------------------------------------------------------------------------
// Telemetry — the top-level registry
// ---------------------------------------------------------------------------

/// Top-level handle that owns the span ring buffer plus the counter / histogram
/// registries. Cheap to clone via `Arc` — typical usage is a single
/// `Arc<Telemetry>` shared across the whole process.
#[derive(Debug)]
pub struct Telemetry {
    span_capacity: usize,
    spans: Mutex<Vec<Span>>,
    counters: RwLock<HashMap<String, Arc<Counter>>>,
    histograms: RwLock<HashMap<String, Arc<Histogram>>>,
}

impl Telemetry {
    /// Build a fresh handle backed by a ring buffer of `span_capacity` spans.
    /// When the buffer fills up, the oldest span is dropped to make room for
    /// the new one — caller is expected to drain via [`Telemetry::dump_spans`]
    /// + a [`NdjsonSpanExporter`] before that happens.
    ///
    /// A `span_capacity` of zero is normalized to 1.
    #[must_use]
    pub fn new(span_capacity: usize) -> Self {
        let cap = span_capacity.max(1);
        Self {
            span_capacity: cap,
            spans: Mutex::new(Vec::with_capacity(cap)),
            counters: RwLock::new(HashMap::new()),
            histograms: RwLock::new(HashMap::new()),
        }
    }

    /// Start a fresh in-flight span. The returned [`SpanHandle`] finalizes the
    /// span on `Drop` with `SpanStatus::Ok` if it has not already been ended.
    ///
    /// If `parent` is supplied, the new span inherits the parent's `TraceId`
    /// (if the parent can be located in the buffer); otherwise a fresh trace
    /// is opened.
    pub fn start_span(
        self: &Arc<Self>,
        name: impl Into<String>,
        kind: SpanKind,
        parent: Option<SpanId>,
    ) -> SpanHandle {
        let id = SpanId::generate();
        let trace_id = parent
            .and_then(|p| self.find_trace_for_span(p))
            .unwrap_or_else(TraceId::generate);
        let span = Span {
            id,
            trace_id,
            parent,
            name: name.into(),
            kind,
            start: Utc::now(),
            end: None,
            status: SpanStatus::Unset,
            attributes: HashMap::new(),
            events: Vec::new(),
        };
        {
            let mut guard = self.spans.lock();
            if guard.len() == self.span_capacity {
                // Drop the oldest span to make room.
                guard.remove(0);
            }
            guard.push(span);
        }
        SpanHandle {
            telemetry: Arc::clone(self),
            id,
            ended: false,
        }
    }

    /// Look up an existing span by id and return its `TraceId`.
    fn find_trace_for_span(&self, id: SpanId) -> Option<TraceId> {
        self.spans
            .lock()
            .iter()
            .find(|s| s.id == id)
            .map(|s| s.trace_id)
    }

    /// Look up or create the named counter. Repeated lookups of the same name
    /// return the same `Arc<Counter>`.
    pub fn counter(&self, name: impl Into<String>) -> Arc<Counter> {
        let name = name.into();
        // Fast path: already registered.
        if let Some(c) = self.counters.read().get(&name) {
            return Arc::clone(c);
        }
        // Slow path: register under the write lock; tolerate a race where two
        // callers raced past the fast-path read.
        let mut guard = self.counters.write();
        guard
            .entry(name.clone())
            .or_insert_with(|| Arc::new(Counter::new(name)))
            .clone()
    }

    /// Look up or create the named histogram with the supplied bucket bounds.
    ///
    /// # Errors
    ///
    /// Returns [`TelemetryError::HistogramBucketsRequired`] if `buckets` is
    /// empty.
    pub fn histogram(
        &self,
        name: impl Into<String>,
        buckets: Vec<f64>,
    ) -> Result<Arc<Histogram>, TelemetryError> {
        let name = name.into();
        if let Some(h) = self.histograms.read().get(&name) {
            return Ok(Arc::clone(h));
        }
        let mut guard = self.histograms.write();
        if let Some(h) = guard.get(&name) {
            return Ok(Arc::clone(h));
        }
        let h = Arc::new(Histogram::new(name.clone(), buckets)?);
        guard.insert(name, Arc::clone(&h));
        Ok(h)
    }

    /// Snapshot every span currently in the ring buffer.
    #[must_use]
    pub fn dump_spans(&self) -> Vec<Span> {
        self.spans.lock().clone()
    }

    /// Atomically drain the ring buffer, returning every recorded span and
    /// leaving the buffer empty. Useful before shutdown export.
    #[must_use]
    pub fn drain_spans(&self) -> Vec<Span> {
        let mut guard = self.spans.lock();
        std::mem::take(&mut *guard)
    }

    /// Snapshot every registered counter and histogram, sorted by name.
    #[must_use]
    pub fn dump_metrics(&self) -> MetricsSnapshot {
        let mut counters: Vec<CounterSnapshot> = self
            .counters
            .read()
            .values()
            .map(|c| CounterSnapshot {
                name: c.name().to_string(),
                value: c.value(),
            })
            .collect();
        counters.sort_by(|a, b| a.name.cmp(&b.name));
        let mut histograms: Vec<HistogramSnapshot> = self
            .histograms
            .read()
            .values()
            .map(|h| h.snapshot())
            .collect();
        histograms.sort_by(|a, b| a.name.cmp(&b.name));
        MetricsSnapshot {
            counters,
            histograms,
        }
    }

    /// Mutate an in-flight span identified by `id`. The closure runs under the
    /// span buffer lock — keep it short.
    fn with_span<R>(&self, id: SpanId, f: impl FnOnce(&mut Span) -> R) -> Option<R> {
        let mut guard = self.spans.lock();
        guard.iter_mut().find(|s| s.id == id).map(f)
    }
}

// ---------------------------------------------------------------------------
// SpanHandle — RAII closer for an in-flight span
// ---------------------------------------------------------------------------

/// RAII handle returned by [`Telemetry::start_span`].
///
/// The handle owns the right to finalize the underlying [`Span`]; dropping it
/// without calling [`SpanHandle::end`] finalizes with [`SpanStatus::Ok`].
///
/// All mutator methods are no-ops once the underlying span has been ended.
#[derive(Debug)]
pub struct SpanHandle {
    telemetry: Arc<Telemetry>,
    id: SpanId,
    ended: bool,
}

impl SpanHandle {
    /// Borrow this handle's span id (useful as a `parent` argument for
    /// subsequent child spans).
    #[must_use]
    pub fn id(&self) -> SpanId {
        self.id
    }

    /// Insert / overwrite an attribute on the underlying span.
    pub fn set_attribute(
        &self,
        key: impl Into<String>,
        value: impl Into<serde_json::Value>,
    ) -> &Self {
        let key = key.into();
        let value = value.into();
        let _ = self.telemetry.with_span(self.id, |s| {
            s.attributes.insert(key, value);
        });
        self
    }

    /// Append a structured event to the underlying span.
    pub fn add_event(
        &self,
        name: impl Into<String>,
        attributes: HashMap<String, serde_json::Value>,
    ) -> &Self {
        let name = name.into();
        let _ = self.telemetry.with_span(self.id, |s| {
            s.add_event(name, attributes);
        });
        self
    }

    /// Assign a non-final status. The status sticks if `end()` is later called
    /// without an explicit override.
    pub fn set_status(&self, status: SpanStatus) -> &Self {
        let _ = self.telemetry.with_span(self.id, |s| {
            s.status = status;
        });
        self
    }

    /// Explicitly close the underlying span with the currently-assigned
    /// status, falling back to [`SpanStatus::Ok`] if none was set. After this
    /// call, every other mutator is a no-op and `Drop` will not double-close.
    pub fn end(mut self) {
        self.finalize_with(None);
    }

    /// Internal: finalize with `status_override` if supplied, else promote
    /// `Unset` to `Ok`.
    fn finalize_with(&mut self, status_override: Option<SpanStatus>) {
        if self.ended {
            return;
        }
        self.ended = true;
        let _ = self.telemetry.with_span(self.id, |s| {
            if s.is_ended() {
                return;
            }
            let final_status = status_override.unwrap_or_else(|| match &s.status {
                SpanStatus::Unset => SpanStatus::Ok,
                other => other.clone(),
            });
            s.end_with_status(final_status);
        });
    }
}

impl Drop for SpanHandle {
    fn drop(&mut self) {
        if !self.ended {
            self.finalize_with(None);
        }
    }
}

// ---------------------------------------------------------------------------
// NdjsonSpanExporter — append-only file sink
// ---------------------------------------------------------------------------

/// Append-only NDJSON file exporter.
///
/// Every call to [`NdjsonSpanExporter::export`] serializes the supplied spans
/// to a UTF-8 buffer (one JSON object per line), then writes them through a
/// `tmp + flush + sync + rename`-style flow that mirrors
/// `aphrody_cron::JsonFileJobStore` and `aphrody_session::JsonlFileStore`.
/// Unlike those crates, *append* semantics are preserved: existing content is
/// read, the new payload is concatenated, and the result is rewritten
/// atomically. That trades raw throughput for crash-safety, which is the
/// right call for a telemetry sink.
#[derive(Debug, Clone)]
pub struct NdjsonSpanExporter {
    path: PathBuf,
}

impl NdjsonSpanExporter {
    /// Build a new exporter rooted at `path`. The parent directory is created
    /// on first export — `new` itself never touches the filesystem.
    pub fn new(path: impl Into<PathBuf>) -> Self {
        Self { path: path.into() }
    }

    /// Borrow the backing file path.
    #[must_use]
    pub fn path(&self) -> &Path {
        &self.path
    }

    /// Serialize `spans` to NDJSON and append them to the backing file.
    ///
    /// # Errors
    ///
    /// Returns [`TelemetryError::Json`] if any span fails to serialize and
    /// [`TelemetryError::Io`] for any filesystem failure.
    pub async fn export(&self, spans: &[Span]) -> Result<(), TelemetryError> {
        if spans.is_empty() {
            return Ok(());
        }
        // Serialize first so we don't touch the filesystem if encoding fails.
        let mut payload = String::new();
        for s in spans {
            let line = serde_json::to_string(s)?;
            payload.push_str(&line);
            payload.push('\n');
        }
        if let Some(parent) = self.path.parent() {
            if !parent.as_os_str().is_empty() {
                afs::create_dir_all(parent).await?;
            }
        }
        // Read the existing file (if any) and concatenate. Atomic rewrite via
        // tmp + flush + sync + rename so concurrent readers never see a torn
        // file.
        let existing = match afs::read(&self.path).await {
            Ok(b) => b,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Vec::new(),
            Err(e) => return Err(e.into()),
        };
        let tmp = self.path.with_extension("ndjson.tmp");
        {
            let mut f = afs::File::create(&tmp).await?;
            if !existing.is_empty() {
                f.write_all(&existing).await?;
                if !existing.ends_with(b"\n") {
                    f.write_all(b"\n").await?;
                }
            }
            f.write_all(payload.as_bytes()).await?;
            f.flush().await?;
            f.sync_all().await?;
        }
        afs::rename(&tmp, &self.path).await?;
        tracing::debug!(
            target: "aphrody_telemetry",
            path = %self.path.display(),
            count = spans.len(),
            "ndjson span batch exported",
        );
        Ok(())
    }
}

