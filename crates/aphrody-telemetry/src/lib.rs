//! aphrody-telemetry — in-process observability primitives for the aphrody runtime.
//!
//! Three primitives, modelled after the OpenTelemetry data model but without
//! pulling in any OTLP / gRPC / protobuf weight:
//!
//! * **Spans** — hierarchical timed work units with attributes, events, and a
//!   final [`SpanStatus`]. Parent/child links carry a [`TraceId`] so a whole
//!   call tree can be reconstructed from a flat dump.
//! * **Counters** — monotonic `u64` accumulators, thread-safe via `AtomicU64`,
//!   intended for "number of HTTP requests served" style metrics.
//! * **Histograms** — bucketed `f64` observations with a sum and count, useful
//!   for latency / request-size distributions. Buckets are caller-supplied
//!   upper bounds; an implicit `+inf` overflow bucket is *not* added, mirroring
//!   the strict OpenTelemetry explicit-bucket histogram contract.
//!
//! ## Cohesion with the wider workspace
//!
//! This crate intentionally complements three sibling crates without
//! overlapping their responsibilities:
//!
//! * **`aphrody-session`** owns the *conversation-level* JSONL log (one file
//!   per session, replayable via `from_jsonl`); telemetry here is the
//!   *operational* log (one append-only NDJSON stream per process run). They
//!   share the monotonic-id + atomic-write patterns but answer different
//!   questions ("what did the model say?" vs "how long did the call take?").
//! * **`aphrody-rateguard`** uses `parking_lot::Mutex` + `AtomicU64` for token
//!   buckets; we reuse the same primitives to keep the lock surface predictable
//!   under concurrent load.
//! * **`aphrody-cron`** writes job manifests with the tokio `tmp + flush + sync
//!   + rename` atomic pattern; we apply the same pattern to NDJSON span batches.
//!
//! ## Example
//!
//! ```no_run
//! use std::sync::Arc;
//! use aphrody_telemetry::{NdjsonSpanExporter, SpanKind, SpanStatus, Telemetry};
//!
//! # async fn run() -> Result<(), aphrody_telemetry::TelemetryError> {
//! let telemetry = Arc::new(Telemetry::new(1024));
//!
//! // Counters & histograms are free to register on the fly.
//! let requests = telemetry.counter("http.requests");
//! let latency  = telemetry.histogram("http.latency_ms", vec![1.0, 10.0, 100.0, 1_000.0]);
//!
//! // Hierarchical spans, RAII-finalized on drop.
//! let parent = telemetry.start_span("handle_request", SpanKind::Server, None);
//! let child  = telemetry.start_span("db.query", SpanKind::Client, Some(parent.id()));
//! child.set_attribute("db.system", "sqlite");
//! latency.observe(8.5);
//! requests.inc();
//! child.end(); // explicit close; otherwise Drop runs with status=Ok
//! parent.set_status(SpanStatus::Ok);
//! parent.end();
//!
//! // Drain & export to NDJSON.
//! let spans = telemetry.dump_spans();
//! NdjsonSpanExporter::new("./var/telemetry/spans.ndjson").export(&spans).await?;
//! # Ok(()) }
//! ```

