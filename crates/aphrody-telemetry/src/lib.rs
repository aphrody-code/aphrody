#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn span_id_display_format() {
        let id = SpanId::from(0xdead_beef_u64);
        assert_eq!(id.to_string(), "span-00000000deadbeef");
    }

    #[test]
    fn trace_id_display_format() {
        let id = TraceId::from(0xcafe_u64);
        assert_eq!(id.to_string(), "trace-000000000000cafe");
    }

    #[test]
    fn telemetry_new_zero_capacity_is_normalized_to_one() {
        let t = Arc::new(Telemetry::new(0));
        let h = t.start_span("only", SpanKind::Internal, None);
        h.end();
        assert_eq!(t.dump_spans().len(), 1);
    }

    #[test]
    fn histogram_requires_buckets() {
        let t = Telemetry::new(8);
        let r = t.histogram("nope", Vec::new());
        assert!(matches!(r, Err(TelemetryError::HistogramBucketsRequired)));
    }

    #[test]
    fn counter_is_shared_across_lookups() {
        let t = Telemetry::new(8);
        let a = t.counter("shared");
        let b = t.counter("shared");
        a.inc();
        b.inc();
        assert_eq!(a.value(), 2);
        assert_eq!(b.value(), 2);
    }
}
